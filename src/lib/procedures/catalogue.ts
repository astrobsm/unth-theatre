// ============================================================
// The seeded procedure catalogue
// ------------------------------------------------------------
// The starting list a surgeon picks from, by subspecialty. It is a STARTING
// list, not a closed one: anything missing can be added at booking time and
// is then permanently available to everybody.
//
// WHERE THE NAMES COME FROM. The body of this list is the hospital's master
// procedure list — "Surgical Consumables & Drugs Shopping Lists", Dr Nnadi
// Emmanuel Chibuike, UNTH Burns/Plastic & Reconstructive Surgery Unit, v1.0,
// November 2026 — transcribed specialty by specialty, with that document's
// own subsection headings kept as the category. Where it names an operation
// this catalogue already carried under different words ("Lipoma excision" for
// "Excision of lipoma"), THE ESTABLISHED NAME IS KEPT. Not out of preference:
// the seed script only ever adds rows, so the other wording would become a
// SECOND row for one operation, sitting next to the first in the dropdown,
// and it would lose the pack mapping attached to the name already in use.
//
// Ophthalmology came separately, as its own list of 575 procedures in the
// same shape (sections A-K, several with numbered subsections), and is merged
// on the same terms.
//
// The subspecialty strings below MUST match surgical_units.subspecialty
// exactly. They are the join key for the dropdown, and a near-miss ("ENT"
// instead of "ENT (Otorhinolaryngology)") produces an empty picker with no
// error — the worst kind of failure. `scripts/lib-tests/procedures.test.ts`
// asserts every key is one of the eleven, and the seed script checks them
// against the live surgical_units table before writing anything.
//
// Scope: what a Nigerian teaching hospital actually does, including the
// emergency workload. Procedures that only exist in centres with facilities
// UNTH does not have are left out — a dropdown of operations nobody can
// perform is noise, and this list is meant to be read at 3 a.m.
// ============================================================

export interface CatalogueEntry {
  name: string;
  /** Grouping within the subspecialty, shown as an optgroup. */
  category: string;
  /**
   * True for procedures commonly done as emergencies. DRIVES ORDERING ONLY —
   * it is not a clinical classification and nothing downstream may treat it
   * as one. Most of these were derived from the name when the master list was
   * transcribed, so a handful read oddly: an interval appendicectomy is an
   * elective operation that happens to be flagged. That costs a place in a
   * dropdown and nothing else.
   */
  emergency?: boolean;
  /**
   * Listed under more than one subspecialty on purpose.
   *
   * Section 11 of the master list — vascular work, surgical access and
   * diagnostic procedures, emergency and damage-control surgery — is
   * explicitly cross-specialty: "They should be included in the master
   * catalogue, with the responsible specialty and alternative eligible
   * specialties properly identified." The unique key is (subspecialty, slug),
   * so the way to say that here is to list the procedure under each unit
   * eligible to book it. The responsible unit is listed first in the source
   * table; after generation they are simply entries like any other.
   */
  crossSpecialty?: boolean;
}

